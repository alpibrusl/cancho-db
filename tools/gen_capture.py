#!/usr/bin/env python3
"""Generate src/capture_sql.cho from sql/capture.sql: the statements the proxy runs at start to install the row-delta capture.

    python3 tools/gen_capture.py          write src/capture_sql.cho
    python3 tools/gen_capture.py --check  fail if the committed module is not what the SQL makes

A statement ends at a `;` outside a `$$ ... $$` body and outside a quoted string; comment lines outside a body are dropped. A cancho string literal is one line, so a
statement is written with `\\n` escapes; the module has `count()` and `stmt(i)`.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SQL = ROOT / "sql/capture.sql"
OUT = ROOT / "src/capture_sql.cho"


def statements(text):
    out, cur, i, n = [], [], 0, len(text)
    in_dollar = in_quote = False
    while i < n:
        c = text[i]
        if in_dollar:
            if text.startswith("$$", i):
                in_dollar = False
                cur.append("$$")
                i += 2
            else:
                cur.append(c)
                i += 1
        elif in_quote:
            cur.append(c)
            if c == "'":
                if text.startswith("''", i):
                    cur.append("'")
                    i += 1
                else:
                    in_quote = False
            i += 1
        elif text.startswith("--", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("$$", i):
            in_dollar = True
            cur.append("$$")
            i += 2
        elif c == "'":
            in_quote = True
            cur.append(c)
            i += 1
        elif c == ";":
            s = "".join(cur).strip()
            if s:
                out.append(s)
            cur = []
            i += 1
        else:
            cur.append(c)
            i += 1
    if "".join(cur).strip():
        raise SystemExit("sql/capture.sql ends inside a statement")
    return out


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"'


def module():
    stmts = statements(SQL.read_text())
    lines = ["module cdb.capture_sql;", "",
             "// capture_sql.cho -- the statements that install the row-delta capture (docs/m2-branches.md D14), one after the other, in the order of sql/capture.sql.",
             "// GENERATED by tools/gen_capture.py from sql/capture.sql: change the SQL, then run it again (`--check` fails when this file is out of date).", "",
             "pub fn count() -> [] int {", "    return %d;" % len(stmts), "}", "",
             "pub fn stmt(i: int) -> [] &static [byte] {"]
    for k, s in enumerate(stmts):
        lines += ["    if i == %d {" % k, "        return %s;" % lit(s), "    }"]
    lines += ['    return "";', "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = module()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("src/capture_sql.cho is not what sql/capture.sql makes: run tools/gen_capture.py")
        print("capture_sql.cho is up to date (%d statements)" % len(statements(SQL.read_text())))
    else:
        OUT.write_text(text)
        print("wrote %s (%d statements)" % (OUT, len(statements(SQL.read_text()))))
